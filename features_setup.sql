-- "¿Quién ha visto tu perfil?"
create table if not exists profile_views (
  id bigint generated by default as identity primary key,
  viewer_id uuid references profiles(id) on delete cascade,
  profile_id uuid references profiles(id) on delete cascade,
  created_at timestamptz default now()
);
create index if not exists idx_profile_views_profile on profile_views(profile_id);

alter table profile_views enable row level security;

-- El dueño del perfil ve quién le ha visto
drop policy if exists "see my viewers" on profile_views;
create policy "see my viewers" on profile_views
  for select using (auth.uid() = profile_id);

-- Cualquiera autenticado puede registrar SU visita
drop policy if exists "log a view" on profile_views;
create policy "log a view" on profile_views
  for insert with check (auth.uid() = viewer_id);


-- Sesiones de estudio (Pomodoro) + ranking
create table if not exists study_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  minutes int not null,
  created_at timestamptz default now()
);
create index if not exists idx_study_user on study_sessions(user_id, created_at);

alter table study_sessions enable row level security;

-- Cada uno inserta lo suyo
drop policy if exists "insert own study" on study_sessions;
create policy "insert own study" on study_sessions
  for insert with check (auth.uid() = user_id);

-- Todos pueden leer (para el ranking con amigos)
drop policy if exists "read study" on study_sessions;
create policy "read study" on study_sessions
  for select using (true);


-- Cosmético: marco/aura del avatar
alter table profiles add column if not exists profile_frame text default 'none';


-- Rutas (tipo Strava)
create table if not exists routes (
  id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  coords jsonb not null,
  distance_m int default 0,
  duration_s int default 0,
  created_at timestamptz default now()
);
create index if not exists idx_routes_user on routes(user_id, created_at);

alter table routes enable row level security;

drop policy if exists "insert own route" on routes;
create policy "insert own route" on routes
  for insert with check (auth.uid() = user_id);

drop policy if exists "read routes" on routes;
create policy "read routes" on routes
  for select using (true);

drop policy if exists "delete own route" on routes;
create policy "delete own route" on routes
  for delete using (auth.uid() = user_id);
